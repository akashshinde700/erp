#!/usr/bin/env python3
"""Derive an isolated SQLite Prisma schema from the production MySQL schema.

This is a TEST-ONLY artifact. It never edits prisma/schema.prisma and never
touches production data: the production deployment keeps its MySQL provider.
It exists so the audit's API/database tests can run offline in this sandbox
(the sandbox cannot reach Prisma's binary CDN or a MySQL server).
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / "prisma" / "schema.prisma").read_text(encoding="utf-8")

# MySQL-specific native types are not supported by the SQLite connector.
src = src.replace('provider = "mysql"', 'provider = "sqlite"', 1)
src = re.sub(r"\s*@db\.Text\b", "", src)
src = re.sub(r"\s*@db\.VarChar\(\d+\)", "", src)
src = src.replace(
    "// MySQL: statuses are String constants, money is Float (r2 discipline); long free text is @db.Text.",
    "// SQLite test variant (generated by tests/make-local-schema.py).",
    1,
)
(ROOT / "tests" / "schema.sqlite.prisma").write_text(src, encoding="utf-8")
print("wrote tests/schema.sqlite.prisma")
